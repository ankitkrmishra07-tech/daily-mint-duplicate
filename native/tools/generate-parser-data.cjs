const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const parser = require('../../node_modules/@babel/parser');
const traverse = require('../../node_modules/@babel/traverse').default;
const root = path.resolve(__dirname, '../..');
const rules = require('../../src/parsers/sms/rules');
const skips = require('../../src/parsers/sms/skipRules');
const { taggingRules } = require('../../src/parsers/common');
const entitySource = fs.readFileSync(path.join(root, 'src/parsers/sms/entityExtractor.js'), 'utf8');
const entityAst = parser.parse(entitySource);
const entities = {};
const context = vm.createContext({});
const nativeEntityRules = {
  accountRules: [/\bAxis Bank\b.{0,60}?\b((?:A\/c|A\/C|Acct|Account)\s+no\.?\s*[Xx*.]*\d+)\b/i],
  debitToRules: [/\b(UPI\/P2M\/\d{12,13}\/[A-Z0-9 .@_*/:-]{2,80}?)(?=\s+Not you\?|\s+SMS\s+BLOCK|\s+-?\s*Axis Bank|$)/i],
  creditFromRules: [/\b(UPI\/P2A\/\d{12,13}\/[A-Z0-9 .@_*/:-]{2,80}?\/UPI)(?=\s*-\s*Axis Bank|$)/i],
};
traverse(entityAst, {
  VariableDeclarator(p) {
    const name = p.node.id.name;
    if (['bankAccountPrefix', 'accountRules', 'debitToRules', 'creditFromRules'].includes(name)) {
      entities[name] = vm.runInContext(entitySource.slice(p.node.init.start, p.node.init.end), context);
      context[name] = entities[name];
    }
  },
});
const literal = value => JSON.stringify(value).replace(/\$/g, '\\$');
const regexList = values => `listOf(${values.map(rule => `Regex(${literal(rule.source)}, RegexOption.IGNORE_CASE)`).join(',\n        ')})`;
let generated = 'package com.ankit.dailymint.core\n\n// Generated by tools/generate-parser-data.cjs from the existing app rules.\ninternal object ParserData {\n';
for (const key of ['debitKeywordRules', 'creditKeywordRules', 'balanceRejectRules']) generated += `    val ${key} = ${regexList(rules[key])}\n`;
for (const key of ['otpSkipRules', 'futureDebitSkipRules', 'cardPaymentAckSkipRules', 'rewardOfferSkipRules']) generated += `    val ${key} = ${regexList(skips[key])}\n`;
for (const key of ['accountRules', 'debitToRules', 'creditFromRules']) {
  generated += `    val ${key} = ${regexList([...nativeEntityRules[key], ...entities[key]])}\n`;
}
generated += `    val banks = listOf(\n${rules.bankAliases.map(b => `        ${literal(b.bank)} to ${regexList(b.patterns)}`).join(',\n')}\n    )\n`;
generated += `    val tags = listOf(\n${taggingRules.map(t => `        ${literal(t.category)} to listOf(${t.keywords.map(literal).join(', ')})`).join(',\n')}\n    )\n}\n`;
const fixtures = fs.readdirSync(path.join(root, 'src/parsers/sms/fixtures')).filter(f => f.endsWith('.json')).flatMap(file => Object.values(JSON.parse(fs.readFileSync(path.join(root, 'src/parsers/sms/fixtures', file), 'utf8')).samples).flat());
let tests = 'package com.ankit.dailymint.core\n\n// Generated from masked regression fixtures; do not add real customer details.\ninternal object SmsFixtures {\n    val values = listOf(\n';
tests += fixtures.map(f => {
  const e = f.expected;
  return `        SmsFixture(${literal(f.id)}, ${literal(f.sms)}, ${e.parsed}, ${e.amount == null ? 'null' : Math.round(e.amount * 100) + 'L'}, ${literal(e.direction ?? null)}, ${literal(e.from ?? null)}, ${literal(e.to ?? null)}, ${literal(e.bank ?? null)}, ${literal(e.reason ?? null)})`;
}).join(',\n') + '\n    )\n}\n';
const outputs = [
  ['shared/src/commonMain/kotlin/com/ankit/dailymint/core/ParserData.kt', generated],
  ['shared/src/commonTest/kotlin/com/ankit/dailymint/core/SmsFixtures.kt', tests],
];
for (const [file, content] of outputs) {
  const output = path.resolve(__dirname, '..', file);
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(output, 'utf8').replace(/\r\n/g, '\n') !== content) throw Error(`Stale generated parser data: ${file}`);
  } else fs.writeFileSync(output, content);
}
console.log(`Checked/generated ${fixtures.length} masked SMS fixtures and shared parser rules.`);
